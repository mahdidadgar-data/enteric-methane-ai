"""
Streamlit app for the Enteric Methane AI project.

The app allows a user to:
    - enter a ruminant diet and animal profile
    - generate an ML-based enteric methane prediction
    - compare the prediction with an empirical/IPCC-style benchmark equation
    - inspect global model drivers
    - view mitigation-opportunity outputs from the explainability pipeline
    - optionally display saved PubMed evidence briefs generated by rag_pubmed.py

Run:
    streamlit run app/app.py

Required previous steps:
    python src/generate_synthetic_data.py
    python src/data_prep.py
    python src/train_models.py
    python src/explain.py
"""

