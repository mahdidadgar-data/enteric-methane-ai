@st.cache_resource
def load_model_bundle(path: Path) -> Dict[str, object]:
    """
    Load trained model bundle.
    """

    return joblib.load(path)


def load_csv_if_exists(path: Path) -> pd.DataFrame | None:
    """
    Read small output files fresh on each rerun.

    Do not cache a missing-file result: a later deployment may add the CSV
    at the same path while the Streamlit process is still running.
    """

    if not path.exists():
        return None

    return pd.read_csv(path)


def display_input_checks(inputs: Dict[str, float | int | str]) -> None:
    """
    Display simple responsible-use checks for unusual user inputs.
    """

    warnings = []

    if float(inputs["forage_pct"]) < 10 or float(inputs["forage_pct"]) > 90:
        warnings.append(
            "Forage percentage is near the edge of the expected range. "
            "The prediction may be less reliable."
        )

    if float(inputs["starch_g_kg"]) > 450:
        warnings.append(
            "Starch level is very high. Interpret methane prediction together "
            "with rumen health and diet formulation constraints."
        )

    if float(inputs["ee_g_kg"]) > 70:
        warnings.append(
            "Dietary fat/ether extract is high. Practical use should consider "
            "intake, digestibility, and animal performance."
        )

    if str(inputs["additive_type"]) != "none" and float(inputs["additive_dose"]) == 0:
        warnings.append(
            "An additive type was selected, but additive dose is 0. "
            "The additive effect may not be represented meaningfully."
        )

    if str(inputs["additive_type"]) == "none" and float(inputs["additive_dose"]) > 0:
        warnings.append(
            "Additive dose is greater than 0 while additive type is 'none'. "
            "The app will still predict, but the input is inconsistent."
        )

    for warning in warnings:
        st.warning(warning)


def show_feature_importance() -> None:
    """
    Show saved global feature importance with its method label.
    """

    importance_df = load_csv_if_exists(FEATURE_IMPORTANCE_PATH)

    if importance_df is None:
        st.info(
            "Feature-importance output was not found. Run "
            "`python src/explain.py` to populate this section."
        )
        return

    top_n = importance_df.head(10).copy()

    st.subheader("Global model drivers: top 10")
    st.caption(
        "These are global drivers of the trained model, not a causal explanation "
        "for one specific farm or ration."
    )
    if "method" in importance_df.columns:
        st.caption("Method: " + "; ".join(importance_df["method"].dropna().unique()))

    st.bar_chart(top_n.set_index("feature")["importance"])

    with st.expander("Show feature-importance table"):
        display_cols = [
            col
            for col in [
                "rank",
                "feature",
                "importance",
                "relative_importance_pct",
                "method",
            ]
            if col in top_n.columns
        ]
        st.dataframe(importance_df[display_cols], width="stretch")


def show_mitigation_opportunities() -> None:
    """
    Show model-based mitigation sensitivity scenarios from explain.py.
    """

    opportunity_df = load_csv_if_exists(MITIGATION_OPPORTUNITY_PATH)

    if opportunity_df is None:
        st.info(
            "Mitigation-opportunity output was not found. Run "
            "`python src/explain.py` to populate this section."
        )
        return

    st.subheader("Model-based mitigation-opportunity sensitivity table")
    st.caption(
        "Negative delta values indicate that the trained model predicts lower "
        "methane yield under that controlled scenario. This is model sensitivity "
        "analysis, not validated ration advice."
    )
    if "reference_kind" in opportunity_df.columns:
        st.info(
            "Precomputed demonstration using 27 synthetic profiles, not real farms "
            "or original training rows. These results do not change with the prediction form. "
            "The scenarios are model-input probes, not fully balanced rations. "
            "Rank is a sorting order, not proven mitigation efficacy."
        )
        st.caption(
            "Delta = scenario mean minus baseline mean, in g CH₄/kg DMI. "
            "Normalized additive dose 1 is not a physical feeding dose and is not "
            "biologically comparable across additives."
        )

    display_cols = [
        col
        for col in [
            "rank",
            "scenario",
            "estimated_delta_g_ch4_kg_dmi",
            "baseline_mean_prediction",
            "intervention_mean_prediction",
            "interpretation",
        ]
        if col in opportunity_df.columns
    ]

    st.dataframe(opportunity_df[display_cols], width="stretch")


def show_rag_briefs() -> None:
    """
    Display saved, source-linked PubMed literature briefs.
    """

    st.subheader("Saved PubMed evidence briefs")

    if not RAG_OUTPUT_DIR.exists():
        st.info(
            "No RAG output folder found yet. Generate an evidence brief from the "
            "command line, for example: "
            '`python src/rag_pubmed.py --topic "3-NOP methane dairy cattle"`'
        )
        return

    brief_files = sorted(RAG_OUTPUT_DIR.glob("evidence_brief_*.md"))

    if not brief_files:
        st.info(
            "No evidence brief files found yet. Generate one with "
            '`python src/rag_pubmed.py --topic "3-NOP methane dairy cattle"`.'
        )
        return

    selected_file = st.selectbox(
        "Select saved evidence brief",
        brief_files,
        format_func=lambda path: path.read_text(encoding="utf-8").splitlines()[0].lstrip("# "),
    )

    st.markdown(selected_file.read_text(encoding="utf-8"))


