bundle = load_model_bundle(MODEL_PATH)
model = bundle["model"]
feature_cols = bundle["feature_cols"]
model_name = bundle.get("model_name", type(model).__name__)

with st.sidebar:
    st.header("Project status")
    st.success("Trained model loaded")
    st.write(f"**Model:** {model_name}")
    st.write(f"**Features:** {len(feature_cols)}")

    st.divider()

    st.caption(
        "Use this app to demonstrate the workflow. Scientific or commercial "
        "decisions require full validation with real data and expert review."
    )

tab_predict, tab_explain, tab_evidence, tab_about = st.tabs(
    [
        "Prediction",
        "Explainability",
        "Evidence briefs",
        "About",
    ]
)

with tab_predict:
    st.header("1. Diet and animal profile")

    col1, col2, col3 = st.columns(3)

    with col1:
        dmi_kg = st.number_input(
            "Dry matter intake (kg/day)",
            min_value=3.0,
            max_value=35.0,
            value=20.0,
            step=0.5,
        )
        cp_g_kg = st.number_input(
            "Crude protein (g/kg DM)",
            min_value=20.0,
            max_value=350.0,
            value=160.0,
            step=1.0,
        )
        ndf_g_kg = st.number_input(
            "NDF (g/kg DM)",
            min_value=50.0,
            max_value=850.0,
            value=400.0,
            step=1.0,
        )
        adf_g_kg = st.number_input(
            "ADF (g/kg DM)",
            min_value=20.0,
            max_value=600.0,
            value=220.0,
            step=1.0,
        )

    with col2:
        ee_g_kg = st.number_input(
            "Ether extract / fat (g/kg DM)",
            min_value=0.0,
            max_value=120.0,
            value=35.0,
            step=1.0,
        )
        starch_g_kg = st.number_input(
            "Starch (g/kg DM)",
            min_value=0.0,
            max_value=550.0,
            value=220.0,
            step=5.0,
        )
        forage_pct = st.slider(
            "Forage proportion (% of diet DM)",
            min_value=0,
            max_value=100,
            value=55,
            step=1,
        )
        st.metric("Concentrate proportion", f"{100 - forage_pct:.0f}%")

    with col3:
        body_weight_kg = st.number_input(
            "Body weight (kg)",
            min_value=250.0,
            max_value=900.0,
            value=575.0,
            step=5.0,
        )
        milk_yield_kg = st.number_input(
            "Milk yield (kg/day)",
            min_value=0.0,
            max_value=70.0,
            value=28.0,
            step=1.0,
        )
        lactating = st.selectbox(
            "Lactation status",
            options=[1, 0],
            format_func=lambda value: "Lactating" if value == 1 else "Non-lactating / dry",
        )
        breed = st.selectbox(
            "Breed",
            options=["Holstein", "Jersey", "Crossbred", "Other"],
        )

    st.subheader("Feed additive")
    col4, col5 = st.columns(2)

    with col4:
        additive_type = st.selectbox(
            "Additive type",
            options=[
                "none",
                "3-NOP",
                "seaweed",
                "tannin",
                "nitrate",
                "lipid",
                "other",
            ],
        )

    with col5:
        additive_dose = st.number_input(
            "Additive dose (normalized units)",
            min_value=0.0,
            max_value=3.0,
            value=0.0,
            step=0.1,
        )

